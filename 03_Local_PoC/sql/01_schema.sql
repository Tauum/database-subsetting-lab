CREATE TABLE organisation(id bigint PRIMARY KEY,name text NOT NULL,contact_email text);
CREATE TABLE process_instance(id bigint PRIMARY KEY,organisation_id bigint REFERENCES organisation(id),state jsonb NOT NULL,status text);
CREATE TABLE application(id bigint PRIMARY KEY,process_id bigint REFERENCES process_instance(id),applicant_name text);
CREATE TABLE participant(id bigint PRIMARY KEY,application_id bigint REFERENCES application(id),referrer_id bigint REFERENCES participant(id),email text);
CREATE TABLE document(id bigint PRIMARY KEY,participant_id bigint REFERENCES participant(id),filename text);
CREATE TABLE attachment(id bigint PRIMARY KEY,document_id bigint REFERENCES document(id),storage_key text);
CREATE TABLE attachment_metadata(id bigint PRIMARY KEY,attachment_id bigint REFERENCES attachment(id),metadata jsonb);
CREATE TABLE task(id bigint PRIMARY KEY,process_id bigint REFERENCES process_instance(id),state jsonb);
CREATE TABLE approval(id bigint PRIMARY KEY,task_id bigint REFERENCES task(id),status text);
CREATE TABLE comment(id bigint PRIMARY KEY,application_id bigint REFERENCES application(id),body text);
CREATE TABLE process_event(id bigint PRIMARY KEY,process_id bigint REFERENCES process_instance(id),payload jsonb);
CREATE TABLE external_reference(id bigint PRIMARY KEY,parent_process_id bigint,reference_code text);
CREATE INDEX idx_process_org ON process_instance(organisation_id);
CREATE INDEX idx_application_process ON application(process_id);
CREATE INDEX idx_external_parent ON external_reference(parent_process_id);
CREATE INDEX idx_process_state ON process_instance USING gin(state);
CREATE TABLE organisation_history(id bigint PRIMARY KEY,record_id bigint,operation text,payload jsonb);
CREATE TABLE process_instance_history(id bigint PRIMARY KEY,record_id bigint,operation text,payload jsonb);
CREATE TABLE application_history(id bigint PRIMARY KEY,record_id bigint,operation text,payload jsonb);
CREATE TABLE participant_history(id bigint PRIMARY KEY,record_id bigint,operation text,payload jsonb);
CREATE TABLE document_history(id bigint PRIMARY KEY,record_id bigint,operation text,payload jsonb);
CREATE TABLE attachment_history(id bigint PRIMARY KEY,record_id bigint,operation text,payload jsonb);
CREATE TABLE attachment_metadata_history(id bigint PRIMARY KEY,record_id bigint,operation text,payload jsonb);
CREATE TABLE task_history(id bigint PRIMARY KEY,record_id bigint,operation text,payload jsonb);
CREATE TABLE approval_history(id bigint PRIMARY KEY,record_id bigint,operation text,payload jsonb);
CREATE TABLE comment_history(id bigint PRIMARY KEY,record_id bigint,operation text,payload jsonb);
CREATE TABLE process_event_history(id bigint PRIMARY KEY,record_id bigint,operation text,payload jsonb);
CREATE TABLE external_reference_history(id bigint PRIMARY KEY,record_id bigint,operation text,payload jsonb);
