"""Write readable table extracts beside a copy of the actual Jailer run evidence."""
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo
import hashlib
import json
import os
import re
import sys
import shutil
import subprocess

root = Path(__file__).resolve().parents[1]
evidence_root = root / 'storage/jailer/work/evidence'
run_name = (evidence_root / 'LATEST.txt').read_text().strip()
capture = evidence_root / run_name
source = json.loads((capture / 'source-before.json').read_text())
extracted = json.loads((capture / 'restored-rows.json').read_text())
tables = list(sorted(source))

def snapshot(schema):
    clauses = [f'''SELECT '{t}' AS table_name, coalesce(jsonb_agg(to_jsonb(t) ORDER BY id), '[]'::jsonb) AS rows FROM {schema}."{t}" t''' for t in tables]
    sql = 'SELECT jsonb_object_agg(table_name, rows) FROM (' + ' UNION ALL '.join(clauses) + ') snapshot'
    out = subprocess.run(['docker', 'compose', 'exec', '-T', 'db', 'psql', '-X', '-U', 'poc', '-d', 'poc_subset', '-At', '-v', 'ON_ERROR_STOP=1', '-c', sql],
                         cwd=root, check=True, capture_output=True, text=True)
    return json.loads(out.stdout)

if snapshot('public') != extracted:
    raise SystemExit('Live unmasked subset differs from captured Jailer evidence; capture a new evidence run first.')
masked = snapshot('masked')
for table in tables:
    if [r['id'] for r in masked[table]] != [r['id'] for r in extracted[table]]:
        raise SystemExit(f'Masked row membership differs: {table}')

jailer_folder = root.parent / '01_Jailer'
destination = jailer_folder / 'evidence/subset-run-evidence'
shutil.copytree(capture, destination, dirs_exist_ok=True)
masking_check = subprocess.run([sys.executable, 'tests/verify_masked_subset.py'], cwd=root, check=True, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
(destination / 'masking-verification.txt').write_text(masking_check.stdout)
(destination / 'masked-rows.json').write_text(json.dumps(masked, indent=2, sort_keys=True) + '\n')

stamp = datetime.now(ZoneInfo('Europe/London')).strftime('%d %B %Y, %H:%M %Z')
lines = [
    '# Jailer lab — readable table extracts', '',
    f'Captured {stamp}. All personal information in this report is fabricated.', '',
    'This report shows every row from all 24 tables at three stages. The source and extracted rows come from the saved Jailer evidence run. The extracted rows were read back after restoring the actual Jailer-generated SQL into a fresh temporary database. The masked rows are a snapshot of the masked schema. The live unmasked subset was checked against the captured extract before this report was written.', '',
    '**Jailer performs the subsetting. Our separate SQL policy performs the masking.** The report formats captured rows; it does not generate or manually select the subset.', '',
    '| Stage | Location | Rows | Tables |', '|---|---|---:|---:|',
]
for title, location, data in [('Source', '`poc.public`', source), ('Jailer extract', '`poc_subset.public`', extracted), ('Masked extract', '`poc_subset.masked`', masked)]:
    lines.append(f'| {title} | {location} | {sum(map(len,data.values()))} | {len(data)} |')
lines += ['', '## What to look for', '',
    '- Process 1001 and participant 3001 survive; the unrelated process 1002 and participant 3002 are excluded.',
    '- Personal details inside process JSON, email columns and free text change in the masked stage.',
    '- The same email gets the same replacement across the participant column, process JSON, task JSON and attachment metadata JSON.',
    '- The malformed submitted date remains `31/99/2026`; the embedded participant reference remains 3001.',
    '- All 12 history tables are included. Both logical external references survive, including the intentionally missing parent.', '',
    '## Run evidence', '',
    f'- [Raw Jailer log](evidence/subset-run-evidence/jailer-export.log)',
    f'- [SQL actually generated by Jailer](evidence/subset-run-evidence/jailer-subset.sql)',
    f'- [Commands, exit codes and fresh-restore checks](evidence/subset-run-evidence/manifest.json)',
    f'- [Original artifact checksums](evidence/subset-run-evidence/SHA256SUMS)',
    f'- [Source row snapshot](evidence/subset-run-evidence/source-before.json)',
    f'- [Freshly restored extract snapshot](evidence/subset-run-evidence/restored-rows.json)',
    f'- [Masked row snapshot](evidence/subset-run-evidence/masked-rows.json)',
    '- [SQL masking policy](../03_Local_PoC/masking/policy.sql)',
    '- [Masking verification](evidence/subset-run-evidence/masking-verification.txt)', '',
    '## Row counts by table', '',
    '| Table | Source | Jailer extract | Masked |', '|---|---:|---:|---:|',
]
for table in tables:
    lines.append(f'| [{table}](#{table}) | {len(source[table])} | {len(extracted[table])} | {len(masked[table])} |')
if (jailer_folder / 'images/intellij-source-er.png').exists():
    lines += ['## IntelliJ schema diagram', '', "Exported directly from IntelliJ IDEA's **Lab — Source** diagram using **Export Diagram → Export to Image** on 14 November 2026. This is the native PNG export, not a recreated drawing. It shows the structure shared by the source, unmasked subset and masked subset.", '', '[Open the full-resolution image](images/intellij-source-er.png) (2152 × 3928 pixels).', '', '![Source schema ER diagram exported directly from IntelliJ IDEA](images/intellij-source-er.png)', '', 'History tables and the logical external reference appear disconnected because those links are not declared foreign keys. Jailer follows the additional logical associations configured in its extraction model; they were not drawn onto this IntelliJ export.', '']

lines += ['', '## Complete table extracts', '',
          'JSON objects are expanded immediately below their row table so nested personal fields and preserved defect values are easy to inspect. SQL NULL is shown as `NULL`.', '']

def cell(value):
    if value is None: return '`NULL`'
    if isinstance(value, (dict, list)): return 'Expanded below'
    return str(value).replace('\\', '\\\\').replace('|', '\\|').replace('\n', ' / ').replace('\r', '')

for table in tables:
    lines += [f'### {table}', '']
    for stage, data in [('Source', source), ('Jailer extract — unmasked', extracted), ('Masked extract', masked)]:
        rows = data[table]
        lines += [f'#### {stage}', '']
        if not rows:
            lines += ['No rows.', '']
            continue
        columns = list(rows[0])
        if 'id' in columns: columns.remove('id'); columns.insert(0, 'id')
        lines += ['| ' + ' | '.join(columns) + ' |', '| ' + ' | '.join(['---'] * len(columns)) + ' |']
        for row in rows:
            lines.append('| ' + ' | '.join(cell(row[column]) for column in columns) + ' |')
        lines.append('')
        for row in rows:
            for column, value in row.items():
                if isinstance(value, (dict, list)):
                    lines += [f'**Row {row["id"]} — `{column}`**', '', '```json', json.dumps(value, indent=2, ensure_ascii=False), '```', '']
lines += ['## Reproduce', '',
    'From the local proof-of-concept folder, capture a fresh run and regenerate this report:', '',
    '```bash', 'python3 jailer/run_with_evidence.py', 'python3 jailer/write_table_report.py', '```', '',
    'The report is a snapshot of this fabricated fixture. It does not demonstrate production anonymisation or large-scale performance. Hashes support later integrity checks; they are not independent third-party attestation.', '']
report = jailer_folder / 'evidence/scenarios/01_subset_and_masking.md'
report.parent.mkdir(parents=True, exist_ok=True)
summary = [
    '## Quick read', '',
    '**One defect example, shown at three stages.** The 24 tables are its related records and history, not 24 separate examples.', '',
    '- **Extract:** Jailer reduced 35 source rows to 25 relevant rows, excluding the unrelated process.',
    '- **Mask:** Our separate SQL step hid names, emails, phone numbers and addresses, including inside JSON.',
    '- **Preserve:** The broken date `31/99/2026`, record IDs and relationships stayed intact.',
    '- **Verify:** The actual Jailer export restored successfully into a fresh database; the checks passed.', '',
    'Everything below is the detailed evidence for that single example. All personal details are fabricated.', '',
]
lines[2:2] = summary
report_text = '\n'.join(lines)
report_text = re.sub(r'## IntelliJ schema diagram\n.*?(?=## Complete table extracts)', '', report_text, flags=re.S)
def rebase_report_link(match):
    target = match[1]
    if target.startswith('#') or '://' in target:
        return match[0]
    return '](' + os.path.relpath((jailer_folder / target).resolve(), report.parent) + ')'
report_text = re.sub(r'\]\(([^)]+)\)', rebase_report_link, report_text)
report.write_text(report_text)
extra = [destination / 'masked-rows.json', report]
(destination / 'REPORT_SHA256SUMS').write_text('\n'.join(hashlib.sha256(p.read_bytes()).hexdigest() + '  ' + str(p.relative_to(jailer_folder)) for p in extra) + '\n')
print(report)
print(f'{len(tables)} tables; source {sum(map(len,source.values()))} rows; extracted {sum(map(len,extracted.values()))}; masked {sum(map(len,masked.values()))}.')
print(f'Evidence copied to {destination}')
